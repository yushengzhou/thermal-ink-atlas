// Generate docs/sources.md from engine/materials.js so the parameter table,
// its sources and the unverified flags cannot drift from the code.
// Usage: node scripts/sources.mjs [--print]
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MATERIALS, MODEL, SOURCES } from '../engine/materials.js';

const cell = (p) => `${p.value} [${p.source}]${p.verified ? '' : ' *unverified*'}`;

export function sourcesMarkdown() {
  const rows = Object.entries(MATERIALS).map(([id, m]) => `| ${m.name} (\`${id}\`) | ${cell(m.alpha)} | ${cell(m.eps)} | ${cell(m.mu)} | ${cell(m.ef)} |`);
  const consts = Object.entries(MODEL).map(([k, p]) => `| \`${k}\` | ${cell(p)} |`);
  return `# Sources and parameters

Generated by \`node scripts/sources.mjs\` from \`engine/materials.js\`; do not edit by hand.
Values marked *unverified* have not been checked against the primary source yet; the
heat cards label them the same way.

## Surface parameters

| Material | albedo α | emissivity ε | admittance μ (J m⁻² s⁻½ K⁻¹) | evaporative fraction |
|---|---|---|---|---|
${rows.join('\n')}

## Model constants

| Constant | Value |
|---|---|
${consts.join('\n')}

## Source keys

${Object.entries(SOURCES).map(([k, v]) => `- **[${k}]** ${v}`).join('\n')}
- **[noaa]** NOAA Global Monitoring Laboratory, General Solar Position Calculations (solareqns.PDF)
- **[brutsaert]** Brutsaert (1975) Water Resources Research 11(5) 742-744, clear-sky emissivity
- **[meinel]** Meinel & Meinel (1976) Applied Solar Energy, clear-sky beam irradiance
- **[solweig]** Lindberg, Holmer & Thorsson (2008) Int. J. Biometeorol. 52, 697-713, SOLWEIG mean radiant temperature
- **[melnikov]** Melnikov et al. (2022) Scientific Reports 12, 2617, doi 10.1038/s41598-022-06383-5, shade and perceived distance

## Equations

- Sun position [noaa]: fractional-year γ, equation of time, declination, true solar time, hour angle → zenith and azimuth.
- Surface energy balance, force-restore [deardorff]:
  dTs/dt = (2√π / (μ√τ))·G − (2π/τ)·(Ts − Td), τ = 86400 s, Td = previous-day mean of Ts (3-day spin-up, 1-min steps).
  G = (1−α)·K↓ + ε·L↓ − εσTs⁴ − h_c·(Ts − Ta) − EF·max(Q*, 0).
- Shortwave: K↓ = sunlit·I_b·sinβ + SVF·D, I_b = 1361·0.7^(AM^0.678) [meinel], D = 0.12·I_b·sinβ [assumed]; tree shade transmits exp(−0.5·LAI) ≈ 0.17.
- Longwave: L↓ = SVF·ε_sky·σTa⁴ + (1−SVF)·σT_wall⁴, ε_sky = 1.24·(e_a/Ta)^(1/7) [brutsaert], T_wall = Ta + 2 K + 6 K·(K↓/900) [assumed].
- Convection: h_c = 5.7 + 3.8·u [oke]; roofs use u × 1.6 [assumed].
- Water: Ts = daily mean Ta − 1 K + 1 K·sin(2π(t − 9 h)/24) [assumed, after the research brief].
- Air temperature: cosine from Ta,min at sunrise to Ta,max at 15:00 and back [assumed].
- Sky view factor: horizon scan, SVF = mean over 16 azimuths of cos²(horizon elevation); canyon check against cos(arctan(2H/W)).
- Mean radiant temperature [solweig], simplified six-direction sum: Tmrt = ((S_str + L_str)/(a_p·σ))^¼ − 273.15, a_k = 0.7, a_p = 0.97, f_p = 0.308·cos(β(1 − β²/48402)).
- Pedestrian route cost [melnikov]: sun distance + 0.84 × building-shade distance + 0.92 × tree-shade distance.
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const md = sourcesMarkdown();
  if (process.argv.includes('--print')) process.stdout.write(md);
  else writeFileSync(fileURLToPath(new URL('../docs/sources.md', import.meta.url)), md);
}
